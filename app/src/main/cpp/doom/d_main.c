//
// D_AddFile
//
void D_AddFile (char *file)
{
    int     numwadfiles;
    char    *newfile;
	
    for (numwadfiles = 0 ; wadfiles[numwadfiles] ; numwadfiles++)
	;

    newfile = malloc (strlen(file)+1);
    strcpy (newfile, file);
	
    wadfiles[numwadfiles] = newfile;
}

//
// IdentifyVersion: IWAD lookup in the directory given by the platform layer.
//
extern const char* I_FindIWAD(const char* name);

static const struct { const char* name; GameMode_t mode; GameMission_t mission; } iwads[] =
{
    { "doom2.wad", commercial, doom2 },
    { "plutonia.wad", commercial, pack_plut },
    { "tnt.wad", commercial, pack_tnt },
    { "doomu.wad", retail, doom },
    { "doom.wad", registered, doom },
    { "doom1.wad", shareware, doom },
    { "freedoom1.wad", retail, doom },
    { "freedoom2.wad", commercial, doom2 },
};

void IdentifyVersion (void)
{
    const char* path;
    unsigned i;

    strcpy(basedefault, "default.cfg");
    for (i = 0; i < sizeof(iwads)/sizeof(iwads[0]); i++)
    {
	path = I_FindIWAD(iwads[i].name);
	if (path)
	{
	    gamemode = iwads[i].mode;
	    gamemission = iwads[i].mission;
	    D_AddFile((char *)path);
	    return;
	}
    }
    gamemode = indetermined;
    I_Error("No IWAD found (doom1.wad / doom.wad / doom2.wad ...)");
}

void D_DoomMain (void)
{
    int p;

    IdentifyVersion ();
    modifiedgame = false;
    nomonsters = M_CheckParm ("-nomonsters");
    respawnparm = M_CheckParm ("-respawn");
    fastparm = M_CheckParm ("-fast");

    p = M_CheckParm ("-playdemo");
    if (!p)
	p = M_CheckParm ("-timedemo");
    if (p && p < myargc-1)
    {
	char file[256];
	sprintf (file,"%s.lmp", myargv[p+1]);
	D_AddFile (file);
    }

    startskill = sk_medium;
    startepisode = 1;
    startmap = 1;
    autostart = false;

    p = M_CheckParm ("-skill");
    if (p && p < myargc-1)
    {
	startskill = myargv[p+1][0]-'1';
	autostart = true;
    }
    p = M_CheckParm ("-warp");
    if (p && p < myargc-1)
    {
	if (gamemode == commercial)
	    startmap = atoi (myargv[p+1]);
	else
	{
	    startepisode = myargv[p+1][0]-'0';
	    startmap = myargv[p+2][0]-'0';
	}
	autostart = true;
    }

    V_Init ();
    M_LoadDefaults ();
    Z_Init ();
    W_InitMultipleFiles (wadfiles);
    M_Init ();
    R_Init ();
    P_Init ();
    I_Init ();
    D_CheckNetGame ();
    S_Init (snd_SfxVolume, snd_MusicVolume);
    HU_Init ();
    ST_Init ();

    p = M_CheckParm ("-playdemo");
    if (p && p < myargc-1)
    {
	singledemo = true;
	G_DeferedPlayDemo (myargv[p+1]);
	D_DoomLoop ();
    }

    p = M_CheckParm ("-timedemo");
    if (p && p < myargc-1)
    {
	G_TimeDemo (myargv[p+1]);
	D_DoomLoop ();
    }

    if (autostart)
	G_InitNew (startskill, startepisode, startmap);
    else
	D_StartTitle ();

    D_DoomLoop ();
}
